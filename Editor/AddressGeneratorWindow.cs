using System;
using System.IO;
using UnityEditor;
using UnityEditor.AddressableAssets;
using UnityEngine;

namespace ResourceLoader.Editor
{
public sealed class AddressGeneratorWindow : EditorWindow
{
    private AddressGeneratorSettings _settings;
    private Vector2 _scroll;
    private string _preview;
    private string _error;

    [MenuItem("Tools/ResourceLoader/Address Generator")]
    private static void Open() => GetWindow<AddressGeneratorWindow>("Resource Addresses");

    private void OnGUI()
    {
        _settings = (AddressGeneratorSettings)EditorGUILayout.ObjectField("Settings", _settings,
            typeof(AddressGeneratorSettings), false);
        if (_settings == null)
        {
            EditorGUILayout.HelpBox("Create or select an Address Generator Settings asset.", MessageType.Info);
            if (GUILayout.Button("Create Settings")) CreateSettings();
            return;
        }

        var serialized = new SerializedObject(_settings);
        EditorGUILayout.PropertyField(serialized.FindProperty("outputPath"));
        EditorGUILayout.PropertyField(serialized.FindProperty("generatedNamespace"));
        EditorGUILayout.PropertyField(serialized.FindProperty("className"));
        EditorGUILayout.PropertyField(serialized.FindProperty("separators"), true);
        EditorGUILayout.PropertyField(serialized.FindProperty("includeGroupName"));
        EditorGUILayout.PropertyField(serialized.FindProperty("pascalCaseNames"));
        EditorGUILayout.PropertyField(serialized.FindProperty("includeAllGroups"));
        serialized.ApplyModifiedProperties();

        var addressables = AddressableAssetSettingsDefaultObject.Settings;
        if (addressables == null)
            EditorGUILayout.HelpBox("Addressables settings are unavailable.", MessageType.Warning);
        else
        {
            if (!_settings.includeAllGroups)
            {
                EditorGUILayout.LabelField("Included groups", EditorStyles.boldLabel);
                foreach (var group in addressables.groups)
                {
                    if (group == null) continue;
                    var selected = _settings.includedGroupNames.Contains(group.Name);
                    var next = EditorGUILayout.ToggleLeft(group.Name, selected);
                    if (next == selected) continue;
                    Undo.RecordObject(_settings, "Change generated Addressables groups");
                    if (next) _settings.includedGroupNames.Add(group.Name);
                    else _settings.includedGroupNames.Remove(group.Name);
                    EditorUtility.SetDirty(_settings);
                }
            }
        }

        if (GUILayout.Button("Preview")) RefreshPreview();
        using (new EditorGUI.DisabledScope(_preview == null || _error != null))
            if (GUILayout.Button("Generate")) GenerateFile();
        if (_error != null) EditorGUILayout.HelpBox(_error, MessageType.Error);
        if (_preview == null) return;
        _scroll = EditorGUILayout.BeginScrollView(_scroll);
        EditorGUILayout.TextArea(_preview, GUILayout.ExpandHeight(true));
        EditorGUILayout.EndScrollView();
    }

    private void CreateSettings()
    {
        var path = EditorUtility.SaveFilePanelInProject("Create Address Generator Settings",
            "AddressGeneratorSettings", "asset", "Choose a settings asset path.");
        if (string.IsNullOrEmpty(path)) return;
        _settings = CreateInstance<AddressGeneratorSettings>();
        AssetDatabase.CreateAsset(_settings, path);
        AssetDatabase.SaveAssets();
    }

    private void RefreshPreview()
    {
        _preview = null;
        _error = null;
        try { _preview = AddressCodeGenerator.Generate(AddressCodeGenerator.ReadAddresses(_settings), _settings); }
        catch (Exception ex) { _error = ex.Message; }
    }

    private void GenerateFile()
    {
        RefreshPreview();
        if (_error != null) return;
        var path = _settings.outputPath.Replace('\\', '/');
        if (!path.StartsWith("Assets/", StringComparison.Ordinal) || !path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) ||
            path.Contains("../") || path.Contains("/.."))
        {
            _error = "Output must be a .cs file below Assets/ without parent traversal.";
            return;
        }
        var folder = Path.GetDirectoryName(path);
        if (!Directory.Exists(folder)) Directory.CreateDirectory(folder);
        if (File.Exists(path) && !File.ReadAllText(path).StartsWith("// <auto-generated />", StringComparison.Ordinal))
        {
            _error = "The output file exists and was not generated by ResourceLoader.";
            return;
        }
        if (File.Exists(path) && File.ReadAllText(path) == _preview) return;
        File.WriteAllText(path, _preview, new System.Text.UTF8Encoding(false));
        AssetDatabase.Refresh();
    }
}
}
